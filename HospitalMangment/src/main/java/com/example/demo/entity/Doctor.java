package com.example.demo.entity;

public class Doctor {

	private String name;
	private String spl;
	private int exp;
	private String  ebducation;
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getSpl() {
		return spl;
	}
	public void setSpl(String spl) {
		this.spl = spl;
	}
	public int getExp() {
		return exp;
	}
	public void setExp(int exp) {
		this.exp = exp;
	}
	public String getEbducation() {
		return ebducation;
	}
	public void setEbducation(String ebducation) {
		this.ebducation = ebducation;
	}
	
	
	
}
